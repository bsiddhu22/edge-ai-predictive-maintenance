#!/usr/bin/env python3
"""Train, quantize and export the motor-condition classifier.

    python ml/train.py [--data data/train.bin]

1. load labeled raw windows from pdm_datagen
2. extract features (ml/features.py == firmware/src/dsp.c)
3. split train/test BY SESSION (windows of one installation never straddle)
4. standardize (train stats only), train a 24-16-4 ReLU MLP
5. int8 post-training quantization, integer reference evaluation
6. export firmware/src/model_data.c, tests/golden/golden.bin, ml/metrics.json
"""
import argparse
import json
import struct
from pathlib import Path

import numpy as np
from sklearn.metrics import confusion_matrix
from sklearn.neural_network import MLPClassifier

import features as F
import quant as Q

ROOT = Path(__file__).resolve().parents[1]
CLASSES = ["NORMAL", "IMBALANCE", "MISALIGNMENT", "BEARING"]


def load(path):
    raw = Path(path).read_bytes()
    assert raw[:4] == b"PDMD", "not a pdm_datagen file"
    n, N, axes = struct.unpack_from("<iii", raw, 4)
    rec = np.dtype([("label", "<i4"), ("session", "<i4"), ("sev", "<f4"), ("frames", "<i2", (N, axes))])
    data = np.frombuffer(raw, dtype=rec, count=n, offset=16)
    return data["frames"].copy(), data["label"].copy(), data["session"].copy(), data["sev"].copy()


def session_split(labels, sessions, frac=0.7, seed=0):
    rng = np.random.default_rng(seed)
    train_s = []
    for c in np.unique(labels):
        s = np.unique(sessions[labels == c])
        rng.shuffle(s)
        train_s.extend(s[: int(round(frac * len(s)))])
    return np.isin(sessions, train_s)


def c_array(name, arr, ctype, per_line=12):
    flat = np.asarray(arr).reshape(-1)
    fmt = (lambda v: f"{v:.9g}f") if ctype == "float" else (lambda v: str(int(v)))
    body = ",\n    ".join(", ".join(fmt(v) for v in flat[i:i + per_line]) for i in range(0, len(flat), per_line))
    return body


def export_c(path, mean, std, q):
    def arr2d(a):
        rows = [", ".join(str(int(v)) for v in r) for r in a]
        return "{\n    {" + "},\n    {".join(rows) + "}\n}"
    src = f"""/* GENERATED by ml/train.py - do not edit. int8 model, TFLite-style quantization. */
#include "model_data.h"

const float nn_feat_mean[NN_IN] = {{
    {c_array('m', mean, 'float', 6)}
}};
const float nn_feat_std[NN_IN] = {{
    {c_array('s', std, 'float', 6)}
}};
const float   nn_in_scale = {q['in_scale']:.9g}f;
const int32_t nn_in_zp = {q['in_zp']};

const int8_t  nn_w1[NN_H][NN_IN] = {arr2d(q['w1'])};
const int32_t nn_b1[NN_H] = {{ {c_array('b1', q['b1'], 'int', 16)} }};
const int32_t nn_m1 = {q['m1']}, nn_s1 = {q['s1']};
const int32_t nn_h_zp = {q['h_zp']};

const int8_t  nn_w2[NN_OUT][NN_H] = {arr2d(q['w2'])};
const int32_t nn_b2[NN_OUT] = {{ {c_array('b2', q['b2'], 'int', 16)} }};
const int32_t nn_m2 = {q['m2']}, nn_s2 = {q['s2']};
const int32_t nn_out_zp = {q['out_zp']};
const float   nn_out_scale = {q['out_scale']:.9g}f;
"""
    Path(path).write_text(src)


def export_golden(path, frames, feats, qin, logits):
    with open(path, "wb") as f:
        f.write(b"PDMG")
        f.write(struct.pack("<iiii", len(frames), frames.shape[1], feats.shape[1], logits.shape[1]))
        for i in range(len(frames)):
            f.write(frames[i].astype("<i2").tobytes())
            f.write(feats[i].astype("<f4").tobytes())
            f.write(qin[i].astype(np.int8).tobytes())
            f.write(logits[i].astype(np.int8).tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "data" / "train.bin"))
    args = ap.parse_args()

    frames, y, sess, sev = load(args.data)
    X = F.features(frames)
    tr = session_split(y, sess)
    te = ~tr
    print(f"windows: {len(y)}  sessions: {len(np.unique(sess))}  "
          f"train sessions: {len(np.unique(sess[tr]))}  test sessions: {len(np.unique(sess[te]))}")

    mean = X[tr].mean(axis=0)
    std = X[tr].std(axis=0) + 1e-6
    Z = (X - mean) / std

    clf = MLPClassifier(hidden_layer_sizes=(16,), activation="relu", alpha=1e-3,
                        max_iter=3000, random_state=0)
    clf.fit(Z[tr], y[tr])
    acc_float = float((clf.predict(Z[te]) == y[te]).mean())

    W1, W2 = clf.coefs_
    b1, b2 = clf.intercepts_
    q = Q.quantize_model(W1, b1, W2, b2, Z[tr])
    qin = Q.quantize_input(Z, q)
    logits = Q.infer_int8(qin, q)
    pred_q = np.argmax(logits, axis=1)
    acc_int8 = float((pred_q[te] == y[te]).mean())
    agree = float((pred_q[te] == clf.predict(Z[te])).mean())

    cm = confusion_matrix(y[te], pred_q[te], labels=range(4))
    print(f"test accuracy  float: {acc_float:.4f}   int8: {acc_int8:.4f}   float/int8 agreement: {agree:.4f}")
    print("int8 confusion (rows = truth):", *CLASSES, sep="\n  ")
    print(cm)

    export_c(ROOT / "firmware" / "src" / "model_data.c", mean, std, q)

    rng = np.random.default_rng(1)
    gold = np.concatenate([rng.choice(np.where(te & (y == c))[0], 4, replace=False) for c in range(4)])
    (ROOT / "tests" / "golden").mkdir(parents=True, exist_ok=True)
    export_golden(ROOT / "tests" / "golden" / "golden.bin", frames[gold], X[gold], qin[gold], logits[gold])

    n_w = q["w1"].size + q["w2"].size
    metrics = {
        "windows": int(len(y)), "train_windows": int(tr.sum()), "test_windows": int(te.sum()),
        "train_sessions": int(len(np.unique(sess[tr]))), "test_sessions": int(len(np.unique(sess[te]))),
        "accuracy_float": round(acc_float, 4), "accuracy_int8": round(acc_int8, 4),
        "float_int8_agreement": round(agree, 4),
        "confusion_int8": cm.tolist(), "classes": CLASSES,
        "model_bytes": {"weights_int8": int(n_w), "biases_int32": int(4 * (q["b1"].size + q["b2"].size)),
                        "float32_equivalent_weights": int(4 * n_w)},
        "per_class_recall_int8": [round(float(cm[i, i] / cm[i].sum()), 4) for i in range(4)],
        "normal_false_positive_rate_per_window": round(float((pred_q[te & (y == 0)] != 0).mean()), 4),
    }
    faulty = te & (y != 0)
    for lo, hi in ((0.1, 0.3), (0.3, 0.6), (0.6, 1.51)):
        m = faulty & (sev >= lo) & (sev < hi)
        metrics[f"fault_recall_severity_{lo}-{min(hi, 1.5)}"] = round(float((pred_q[m] == y[m]).mean()), 4)
    print({k: v for k, v in metrics.items() if k.startswith(("fault_recall", "normal_false"))})
    (ROOT / "ml" / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print("exported firmware/src/model_data.c, tests/golden/golden.bin, ml/metrics.json")


if __name__ == "__main__":
    main()
